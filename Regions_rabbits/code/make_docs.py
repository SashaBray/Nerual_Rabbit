def img(doc, path, width=6.3, caption=None):
    if os.path.exists(path):
        doc.add_picture(path, width=Inches(width))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        if caption:
            c = doc.add_paragraph(caption); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = c.runs[0]; r.italic = True; r.font.size = Pt(9)
    else:
        doc.add_paragraph(f'[график не найден: {path}]')


def kv(doc, pairs):
    for k, v in pairs:
        p = doc.add_paragraph(style='List Bullet')
        r = p.add_run(f'{k}: '); r.bold = True
        p.add_run(str(v))


def fail(doc, symptom, cause, fix=None):
    """Запись о неудаче: жирный симптом — Причина — Решение."""
    p = doc.add_paragraph(style='List Bullet')
    r = p.add_run(symptom + '  '); r.bold = True
    rc = p.add_run('Причина: '); rc.italic = True
    p.add_run(cause)
    if fix:
        rf = p.add_run('  Решение: '); rf.italic = True
        p.add_run(fix)


